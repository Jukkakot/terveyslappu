def build(rows):
    seen = {}
    out = []
    for i, row in enumerate(rows):
        if len(row) != 6:
            sys.exit(f"row {i}: expected 6 fields: {row!r}")
        name, per, kcal, portion, treat, aliases = row
        if per not in ("100g", "kpl"):
            sys.exit(f"{name}: invalid per {per!r}")
        if not isinstance(kcal, (int, float)) or kcal <= 0:
            sys.exit(f"{name}: kcal must be > 0")
        if not isinstance(portion, (int, float)) or portion <= 0:
            sys.exit(f"{name}: portion must be > 0")
        for label in [name] + list(aliases):
            key = label.strip().lower()
            if not key:
                sys.exit(f"{name}: empty name/alias")
            if key in seen:
                sys.exit(f"duplicate name/alias {label!r} (also in {seen[key]!r})")
            seen[key] = name
        entry = {"name": name}
        if aliases:
            entry["aliases"] = list(aliases)
        entry["per"] = per
        entry["kcal"] = kcal if isinstance(kcal, float) and kcal != int(kcal) else int(kcal)
        entry["portion"] = int(portion) if portion == int(portion) else portion
        if treat:
            entry["treat"] = True
        out.append(entry)
    out.sort(key=lambda e: e["name"].lower())
    return out


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "app", "src", "main", "assets", "base-products.json")
    data = build(PRODUCTS)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"wrote {len(data)} products to {path}")


if __name__ == "__main__":
    main()
